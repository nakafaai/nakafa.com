/** One plant's family and coat, by its place in the catalog. */
export function plantLookOf(index: number) {
  const [family, [petal, heart, leaf], wild] = PLANT_LOOKS[PLANT_KEYS[index]];
  return {
    coat: { accent: leaf, belly: heart, body: petal, mark: petal },
    family,
    wild,
  };
}

/** The plants that grow wild on the meadows, by their place in the catalog. */
export const WILD_PLANTS = Arr.filter(
  Arr.makeBy(PLANT_KEYS.length, (index) => index),
  (index) => PLANT_LOOKS[PLANT_KEYS[index]][2]
);
