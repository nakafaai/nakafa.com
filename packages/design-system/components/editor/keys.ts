/** One set of keys, which the keypad's tabs choose. */
export type KeySet = keyof typeof KEY_SETS;

/** The key that names each set in its tab, drawn as the formula it stands for. */
export const SET_SIGNS = {
  chemistry: String.raw`\ce{H2O}`,
  functions: "f(x)",
  greek: String.raw`\alpha\beta`,
  numbers: "123",
  physics: String.raw`\vec{F}`,
  symbols: String.raw`\le`,
} satisfies Record<KeySet, string>;

/** An empty slot of a key, which its face shows as an empty square. */
const SLOT = /#[?@]/gu;

/** What a key draws: its LaTeX with each slot shown as an empty square. */
export const keyFace = (latex: string) =>
  latex.replaceAll(SLOT, String.raw`\square`);
